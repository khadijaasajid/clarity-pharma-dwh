-- This script runs automatically when postgres-staging container starts for the first time
-- It creates the staging schema and raw tables to receive CSV data

CREATE SCHEMA IF NOT EXISTS raw;

-- 01_master_data: Medicine master reference
CREATE TABLE IF NOT EXISTS raw.master_data (
    medicine_id VARCHAR(20),
    medicine_name VARCHAR(200),
    generic_name VARCHAR(200),
    brand_name VARCHAR(200),
    manufacturer VARCHAR(200),
    dosage_form VARCHAR(100),
    strength VARCHAR(100),
    unit_of_measure VARCHAR(50),
    pack_size INTEGER,
    therapeutic_class VARCHAR(200),
    disease_category VARCHAR(200),
    drug_schedule VARCHAR(50),
    prescription_type VARCHAR(100),
    storage_condition VARCHAR(100),
    shelf_life_months INTEGER,
    reorder_level_packs INTEGER,
    unit_cost_usd NUMERIC(12,4),
    unit_retail_price_usd NUMERIC(12,4),
    is_active BOOLEAN,
    launch_date DATE,
    country_of_origin VARCHAR(100),
    fda_approved BOOLEAN,
    controlled_substance BOOLEAN,
    cold_chain_required BOOLEAN,
    hazardous_material BOOLEAN,
    batch_tracking_required BOOLEAN,
    serial_tracking_required BOOLEAN,
    max_daily_dose VARCHAR(100),
    contraindications TEXT,
    side_effects TEXT,
    drug_interactions TEXT,
    pregnancy_category VARCHAR(10),
    pediatric_use BOOLEAN,
    geriatric_use BOOLEAN
);

-- 05_pharmacy_sales_data: Transactional sales
CREATE TABLE IF NOT EXISTS raw.pharmacy_sales (
    sales_transaction_id VARCHAR(50),
    pharmacy_id VARCHAR(20),
    pharmacy_name VARCHAR(200),
    pharmacy_type VARCHAR(100),
    pharmacy_city VARCHAR(100),
    pharmacy_state VARCHAR(100),
    pharmacy_region VARCHAR(100),
    medicine_id VARCHAR(20),
    sales_date DATE,
    sales_timestamp_utc TIMESTAMP,
    quantity_sold_packs INTEGER,
    unit_retail_price_usd NUMERIC(12,4),
    gross_sales_amount_usd NUMERIC(14,4),
    discount_percentage NUMERIC(5,2),
    discount_amount_usd NUMERIC(14,4),
    net_sales_amount_usd NUMERIC(14,4),
    tax_rate NUMERIC(5,2),
    tax_amount_usd NUMERIC(14,4),
    cogs_amount_usd NUMERIC(14,4),
    gross_margin_usd NUMERIC(14,4),
    payment_method VARCHAR(50),
    insurance_coverage VARCHAR(50),
    customer_segment VARCHAR(100),
    prescription_id VARCHAR(50),
    prescription_required BOOLEAN,
    sales_channel VARCHAR(50),
    promotion_code VARCHAR(50),
    batch_number VARCHAR(50),
    batch_expiry_date DATE,
    days_to_expiry_at_sale INTEGER,
    returned_quantity_packs INTEGER,
    return_reason VARCHAR(200),
    pharmacy_order_id VARCHAR(50),
    pharmacy_delivery_id VARCHAR(50),
    pharmacy_delivery_date DATE,
    is_emergency_order BOOLEAN,
    line_item_count INTEGER,
    customer_loyalty_tier VARCHAR(50),
    referring_physician VARCHAR(200),
    is_generic_substitution BOOLEAN,
    is_cold_chain_product BOOLEAN,
    storage_temp_maintained BOOLEAN,
    dispensing_pharmacist_id VARCHAR(50),
    notes TEXT,
    last_updated TIMESTAMP
);

-- 06_hospital_demand_data: Monthly periodic snapshot
CREATE TABLE IF NOT EXISTS raw.hospital_demand (
    hospital_demand_record_id VARCHAR(50),
    hospital_id VARCHAR(20),
    hospital_name VARCHAR(200),
    hospital_type VARCHAR(100),
    bed_capacity INTEGER,
    has_pharmacy_unit BOOLEAN,
    accreditation_status VARCHAR(100),
    funding_type VARCHAR(100),
    emergency_level VARCHAR(50),
    operating_status VARCHAR(50),
    hospital_city VARCHAR(100),
    hospital_state VARCHAR(100),
    hospital_region VARCHAR(100),
    medicine_id VARCHAR(20),
    demand_month DATE,
    forecast_demand_packs INTEGER,
    actual_consumption_packs INTEGER,
    unfulfilled_demand_packs INTEGER,
    opening_stock_packs INTEGER,
    closing_stock_packs INTEGER,
    quantity_received_packs INTEGER,
    quantity_expired_packs INTEGER,
    stockout_days INTEGER,
    emergency_order_count INTEGER,
    emergency_order_cost_usd NUMERIC(14,4),
    wastage_value_usd NUMERIC(14,4),
    inventory_carrying_cost_usd NUMERIC(14,4),
    budget_variance_usd NUMERIC(14,4),
    service_level_pct NUMERIC(5,2),
    demand_trend_index NUMERIC(8,4),
    average_lead_time_days NUMERIC(8,2),
    safety_stock_packs INTEGER,
    days_of_supply INTEGER,
    supplier_reliability_score NUMERIC(5,2),
    order_frequency VARCHAR(50),
    procurement_method VARCHAR(100),
    contract_price_usd NUMERIC(12,4),
    substitution_allowed BOOLEAN,
    therapeutic_committee_approved BOOLEAN,
    notes TEXT,
    last_updated TIMESTAMP
);
